namespace DigitWindowsBLE;
internal static class HidProfile
{
    public static Guid Uuid(ushort shortId) => new Guid($"0000{shortId:x4}-0000-1000-8000-00805f9b34fb");
    // Keyboard-only, Report protocol, Report ID 1. GATT report payload omits the ID.
    // 8 modifier bits + reserved byte + six 8-bit key usages = 8 bytes.
    public static readonly byte[] ReportMap = {
        0x05,0x01, 0x09,0x06, 0xA1,0x01, 0x85,0x01,
        0x05,0x07, 0x19,0xE0, 0x29,0xE7, 0x15,0x00, 0x25,0x01,
        0x75,0x01, 0x95,0x08, 0x81,0x02,
        0x75,0x08, 0x95,0x01, 0x81,0x01,
        0x05,0x07, 0x19,0x00, 0x29,0x65, 0x15,0x00, 0x25,0x65,
        0x75,0x08, 0x95,0x06, 0x81,0x00, 0xC0
    };
    public static readonly byte[] ReportReference = { 0x01, 0x01 }; // id=1, input
    public static readonly byte[] HidInformation = { 0x11, 0x01, 0x00, 0x02 }; // HID 1.11, no remote wake
}
